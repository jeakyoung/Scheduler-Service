-- H2 equivalent of ../V1__schedule_core.sql - used ONLY as the local-dev fallback meta DB
-- when DB_URL is unset (PLAN.md's H2 fallback feature). The SQL-Server migration this
-- mirrors is never edited - H2 needs genuinely different DDL syntax (IDENTITY generation,
-- no NVARCHAR(MAX)/DATETIME2/SYSUTCDATETIME()), not just a dialect tweak, so it gets its
-- own migration set rather than trying to force one script to parse under both engines.
-- Column shapes/constraints are otherwise identical to the SQL Server version.

CREATE TABLE target_db_config (
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name                VARCHAR(100)    NOT NULL,
    jdbc_url            VARCHAR(500)    NOT NULL,
    username            VARCHAR(200)    NOT NULL,
    encrypted_password  CLOB            NOT NULL,
    created_at          TIMESTAMP       NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at          TIMESTAMP       NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE credential (
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name                VARCHAR(100)    NOT NULL,
    encrypted_value     CLOB            NOT NULL,
    description         VARCHAR(300)    NULL,
    updated_at          TIMESTAMP       NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_by          VARCHAR(100)    NULL,
    CONSTRAINT UQ_credential_name UNIQUE (name)
);

CREATE TABLE admin_user (
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username            VARCHAR(100)    NOT NULL,
    password_hash       VARCHAR(200)    NOT NULL,
    role                VARCHAR(20)     NOT NULL DEFAULT 'ADMIN',
    created_at          TIMESTAMP       NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT UQ_admin_user_username UNIQUE (username)
);

CREATE TABLE schedule_definition (
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name                VARCHAR(200)    NOT NULL,
    enabled             BOOLEAN         NOT NULL DEFAULT FALSE,
    cron_expression     VARCHAR(100)    NOT NULL,
    timezone            VARCHAR(50)     NOT NULL DEFAULT 'Asia/Seoul',
    sp_name             VARCHAR(200)    NOT NULL,
    target_db_config_id BIGINT          NOT NULL,
    action_type         VARCHAR(20)     NOT NULL,
    action_config       CLOB            NOT NULL,
    description         VARCHAR(500)    NULL,
    created_at          TIMESTAMP       NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at          TIMESTAMP       NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_by          VARCHAR(100)    NULL,
    CONSTRAINT FK_schedule_definition_target_db_config
        FOREIGN KEY (target_db_config_id) REFERENCES target_db_config (id)
);

CREATE TABLE schedule_parameter (
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    schedule_id         BIGINT          NOT NULL,
    param_order         INT             NOT NULL,
    param_name          VARCHAR(100)    NOT NULL,
    data_type           VARCHAR(20)     NOT NULL,
    value_source        VARCHAR(20)     NOT NULL,
    literal_value       VARCHAR(500)    NULL,
    CONSTRAINT FK_schedule_parameter_schedule_definition
        FOREIGN KEY (schedule_id) REFERENCES schedule_definition (id) ON DELETE CASCADE
);

CREATE INDEX IX_schedule_parameter_schedule_id ON schedule_parameter (schedule_id);
